param([string]$Dump = "$env:APPDATA\Factorio\script-output\data-raw-dump.json")
# Some mods build an item's name as {item.type .. "-name." .. item.name} (Factorio 1.x style), e.g. Transport Drones'
# request recipes. In 2.x every item type uses item-name, so the game shows 'Unknown key: "tool-name.kr-basic-tech-card"'.
# This writes locale\uk\type-name-fixes.cfg: [<type>-name] <item>=__ITEM__<item>__ for every such key the data uses.
# Needs a fresh data dump of the installed modset (close Factorio first):
#   factorio.exe --mod-directory "E:\games\mods\Factorio" --dump-data   (writes %APPDATA%\Factorio\script-output\data-raw-dump.json)
$ErrorActionPreference = 'Stop'
$out = 'E:\games\mods\locale\ukrainian-mods-translation\locale\uk\type-name-fixes.cfg'
$itemTypes = @('ammo','armor','capsule','gun','item-with-entity-data','item-with-inventory','item-with-label','item-with-tags',
  'module','rail-planner','repair-tool','selection-tool','blueprint','blueprint-book','copy-paste-tool','deconstruction-item',
  'upgrade-item','spidertron-remote','tool','space-platform-starter-pack')
$items = @{}; $used = @{}; $typ = ''
$re = [regex]('"((?:' + (($itemTypes | ForEach-Object { [regex]::Escape($_) }) -join '|') + ')-name)\.([^"]+)"')
$sr = New-Object IO.StreamReader($Dump, [Text.Encoding]::UTF8)
while ($null -ne ($l = $sr.ReadLine())) {
  if ($l.StartsWith('  "') -and -not $l.StartsWith('   ')) { $typ = $l.Trim().TrimEnd(':', ' ').Trim('"'); continue }
  if ($l.StartsWith('    "') -and -not $l.StartsWith('     ') -and $l.TrimEnd().EndsWith(':')) {
    if ($itemTypes -contains $typ) { $items["$typ-name`t" + $l.Trim().TrimEnd(':', ' ').Trim('"')] = 1 }
    continue
  }
  if ($l.IndexOf('-name.') -ge 0) { foreach ($m in $re.Matches($l)) { $used[$m.Groups[1].Value + "`t" + $m.Groups[2].Value] = 1 } }
}
$sr.Close()
# keep keys from the previous run (mods that are not installed now may come back; the keys are harmless)
$prev = 0
if (Test-Path $out) {
  $sec = ''
  foreach ($l in [IO.File]::ReadAllLines($out, [Text.Encoding]::UTF8)) {
    if ($l -match '^\[(.+)\]$') { $sec = $matches[1]; continue }
    if ($l -match '^([^;=][^=]*)=__ITEM__') { $k = "$sec`t" + $matches[1]; if (-not $used.ContainsKey($k)) { $used[$k] = 1; $items[$k] = 1; $prev++ } }
  }
}
$bySec = [ordered]@{}
foreach ($k in ($used.Keys | Sort-Object)) {
  if (-not $items.ContainsKey($k)) { continue }   # only real items of that type (mods may define such sections themselves)
  $sec, $name = $k -split "`t", 2
  if (-not $bySec.Contains($sec)) { $bySec[$sec] = New-Object System.Collections.Generic.List[string] }
  $bySec[$sec].Add("$name=__ITEM__$($name)__")
}
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('; Generated by tools/type-name-fixes.ps1: <type>-name.<item> keys that mods still reference (1.x style).')
$n = 0
foreach ($s in $bySec.Keys) {
  [void]$sb.AppendLine(''); [void]$sb.AppendLine("[$s]")
  foreach ($l in $bySec[$s]) { [void]$sb.AppendLine($l); $n++ }
}
[IO.File]::WriteAllText($out, ($sb.ToString() -replace "\r?\n", "`r`n"), (New-Object Text.UTF8Encoding($false)))
"type-name-fixes.cfg: $n keys in $($bySec.Count) sections"
