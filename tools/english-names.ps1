param([switch]$MoveExisting)
# User rules: mod names and alien-biomes tree names stay untranslated (English); see also CLAUDE.md (planet names).
# -MoveExisting: one-off - move [mod-name] keys out of our pack files into inactive-translations.cfg (kept, not shipped).
# Always: regenerate locale/uk/english-names.cfg = English text for keys some mod's uk translates:
#   [mod-name] of every installed mod (e.g. Krastorio2's own uk), and alien-biomes tree names (species and
#   tree colour names from prototypes/entity/tree-*.lua plus the ab-tree / ab-stump formats).
#   Colour keys alien-biomes also uses for tiles/decoratives (listed before ab-tree in its en locale) stay translated.
# Our own mod keeps its title (it is Ukrainian by design).
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$myDir = "$root\ukrainian-mods-translation\locale\uk"
$utf8 = New-Object Text.UTF8Encoding($false)
$self = 'ukrainian-mods-translation'

function ParseFiles($files) {
  $h = [ordered]@{}
  foreach ($f in $files) {
    $sec = ''
    foreach ($l in [IO.File]::ReadAllLines($f, [Text.Encoding]::UTF8)) {
      $t = $l.TrimStart([char]0xFEFF).Trim()
      if ($t -eq '' -or $t[0] -eq ';' -or $t[0] -eq '#') { continue }
      if ($t -match '^\[(.+)\]$') { $sec = $matches[1].Trim(); continue }
      $i = $t.IndexOf('='); if ($i -lt 1) { continue }
      $h["$sec`t" + $t.Substring(0, $i).Trim()] = $t.Substring($i + 1)
    }
  }
  return $h
}
function ParseDir($dir) {
  if (-not (Test-Path $dir)) { return [ordered]@{} }
  return ParseFiles @(Get-ChildItem $dir -Filter *.cfg | Sort-Object Name | ForEach-Object { $_.FullName })
}

if ($MoveExisting) {
  $moved = New-Object Text.StringBuilder
  foreach ($f in Get-ChildItem $myDir -Filter *.cfg | Where-Object { $_.Name -notlike 'own-*' -and $_.Name -ne 'english-names.cfg' } | Sort-Object Name) {
    $text = [IO.File]::ReadAllText($f.FullName, [Text.Encoding]::UTF8)
    $nl = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
    $lines = $text -split "\r?\n"
    $out = New-Object System.Collections.Generic.List[string]; $sec = ''; $took = @()
    foreach ($l in $lines) {
      $t = $l.Trim()
      if ($t -match '^\[(.+)\]$') { $sec = $matches[1].Trim() }
      elseif ($sec -eq 'mod-name' -and $t -ne '' -and $t[0] -ne ';' -and $t.IndexOf('=') -gt 0 -and $t -notlike "$self=*") {
        $took += $t; continue
      }
      $out.Add($l)
    }
    if ($took.Count -eq 0) { continue }
    # drop a [mod-name] header left without keys (and the blank line before it)
    for ($i = $out.Count - 1; $i -ge 0; $i--) {
      if ($out[$i].Trim() -ne '[mod-name]') { continue }
      $j = $i + 1; while ($j -lt $out.Count -and $out[$j].Trim() -eq '') { $j++ }
      if ($j -ge $out.Count -or $out[$j].Trim() -match '^\[') {
        $out.RemoveAt($i); if ($i -gt 0 -and $out[$i - 1].Trim() -eq '') { $out.RemoveAt($i - 1) }
      }
    }
    [IO.File]::WriteAllText($f.FullName, ($out -join $nl), $utf8)
    [void]$moved.AppendLine("; ===== from $($f.Name) =====")
    [void]$moved.AppendLine('[mod-name]')
    foreach ($t in $took) { [void]$moved.AppendLine('; MOD NAME (user rule: mod names stay English)'); [void]$moved.AppendLine($t) }
    [void]$moved.AppendLine('')
    "{0,-28} moved {1}" -f $f.Name, $took.Count
  }
  if ($moved.Length) {
    $inact = "$root\inactive-translations.cfg"
    $head = "`r`n; ===== moved 2026-10-12: mod names stay untranslated (user rule) =====`r`n"
    [IO.File]::AppendAllText($inact, $head + ($moved.ToString() -replace "\r?\n", "`r`n"), $utf8)
  }
}

# English names of installed mods, and every uk translation of a mod name found in any mod
$enName = @{}; $ukNamed = @{}
foreach ($d in Get-ChildItem "$root\mods" -Directory) {
  if ($d.Name -like "$self*") { continue }
  $ij = Join-Path $d.FullName 'info.json'; if (-not (Test-Path $ij)) { continue }
  $info = Get-Content $ij -Raw -Encoding UTF8 | ConvertFrom-Json
  $en = ParseDir "$($d.FullName)\locale\en"
  $k = "mod-name`t$($info.name)"
  $enName[$info.name] = if ($en.Contains($k)) { $en[$k] } elseif ($info.title) { $info.title } else { $info.name }
  $uk = ParseDir "$($d.FullName)\locale\uk"
  foreach ($key in $uk.Keys) { if ($key -like "mod-name`t*") { $ukNamed[$key.Substring(9)] = $uk[$key] } }
}
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('; Names that stay English (user rules). Generated by tools/english-names.ps1 - overrides mods'' own uk.')
[void]$sb.AppendLine('[mod-name]')
$n = 0
foreach ($m in ($ukNamed.Keys | Sort-Object)) {
  if ($m -eq $self -or -not $enName.ContainsKey($m)) { continue }
  if ($ukNamed[$m] -eq $enName[$m]) { continue }
  [void]$sb.AppendLine("$m=$($enName[$m])"); $n++
}
# alien-biomes tree names
$ab = Get-ChildItem "$root\mods" -Directory | Where-Object { $_.Name -like 'alien-biomes_*' -and (Test-Path "$($_.FullName)\info.json") } | Select-Object -First 1
if ($ab) {
  $en = ParseDir "$($ab.FullName)\locale\en"; $uk = ParseDir "$($ab.FullName)\locale\uk"
  $shared = @{}
  foreach ($l in [IO.File]::ReadAllLines("$($ab.FullName)\locale\en\strings.cfg", [Text.Encoding]::UTF8)) {
    if ($l -like 'ab-tree=*') { break }
    $i = $l.IndexOf('='); if ($i -gt 0) { $shared[$l.Substring(0, $i).Trim()] = 1 }
  }
  $keys = New-Object System.Collections.Generic.List[string]; $keys.Add('ab-tree'); $keys.Add('ab-stump')
  foreach ($lua in Get-ChildItem "$($ab.FullName)\prototypes\entity" -Filter 'tree-*.lua') {
    foreach ($m in [regex]::Matches([IO.File]::ReadAllText($lua.FullName), 'locale\s*=\s*"([^"]+)"')) {
      $k = $m.Groups[1].Value; if (-not $shared.ContainsKey($k) -and -not $keys.Contains($k)) { $keys.Add($k) }
    }
  }
  [void]$sb.AppendLine(''); [void]$sb.AppendLine('[alien-biomes]')
  foreach ($k in $keys) {
    $sk = "alien-biomes`t$k"
    if (-not $en.Contains($sk) -or -not $uk.Contains($sk) -or $uk[$sk] -eq $en[$sk]) { continue }
    [void]$sb.AppendLine("$k=$($en[$sk])"); $n++
  }
}
$out = "$myDir\english-names.cfg"
if ($n) { [IO.File]::WriteAllText($out, ($sb.ToString() -replace "\r?\n", "`r`n"), $utf8) } elseif (Test-Path $out) { Remove-Item $out }
"english-names.cfg: $n English overrides"
